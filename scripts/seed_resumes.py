def _markdown(resume: dict) -> str:
    lines = [f"# {resume['name']}", f"**{resume['role']}** · {resume['city']}", ""]
    lines.append(f"{resume['phone']} · {resume['email']}")
    lines.append("")
    for heading, items in resume["sections"]:
        lines.append(f"## {heading}")
        lines.append("")
        for item in items:
            if item.startswith("- "):
                lines.append(f"- {item[2:]}")
            else:
                lines.append(item)
                lines.append("")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_docx(resume: dict, path: Path) -> None:
    pandoc = shutil.which("pandoc")
    if not pandoc:
        raise RuntimeError("pandoc is required to build DOCX resumes")
    subprocess.run(
        [pandoc, "-f", "markdown", "-t", "docx", "--output", str(path)],
        input=_markdown(resume).encode("utf-8"),
        check=True,
    )


def _pdf_story(resume: dict, accent: str):
    from reportlab.lib.colors import HexColor
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import HRFlowable, Paragraph, Spacer

    body = ParagraphStyle(
        "body",
        fontName="Arial",
        fontSize=9.6,
        leading=13,
        alignment=TA_LEFT,
        spaceAfter=4,
        textColor=HexColor("#111111"),
    )
    bullet = ParagraphStyle("bullet", parent=body, leftIndent=10, firstLineIndent=-9)
    heading = ParagraphStyle(
        "heading",
        fontName="Arial-Bold",
        fontSize=11.5,
        leading=14,
        spaceBefore=9,
        spaceAfter=4,
        textColor=HexColor(accent),
    )
    name = ParagraphStyle(
        "name",
        fontName="Arial-Bold",
        fontSize=19,
        leading=23,
        spaceAfter=2,
        textColor=HexColor(accent),
    )
    subtitle = ParagraphStyle(
        "subtitle", fontName="Arial", fontSize=10.5, leading=14, textColor=HexColor("#333333")
    )
    contacts = ParagraphStyle(
        "contacts", fontName="Arial", fontSize=9.2, leading=12, textColor=HexColor("#444444")
    )

    story = [
        Paragraph(escape(resume["name"]), name),
        Paragraph(escape(f"{resume['role']} · {resume['city']}"), subtitle),
        Spacer(1, 3 * mm),
        Paragraph(
            escape(f"{resume['phone']} · {resume['email']}"), contacts
        ),
        Spacer(1, 3 * mm),
        HRFlowable(width="100%", thickness=0.8, color=HexColor(accent), spaceAfter=2),
    ]
    for section_heading, items in resume["sections"]:
        story.append(Paragraph(escape(section_heading), heading))
        for item in items:
            is_bullet = item.startswith("- ")
            text = item[2:] if is_bullet else item
            story.append(
                Paragraph(escape(("• " if is_bullet else "") + text), bullet if is_bullet else body)
            )
    return story


def render_pdf(resume: dict, path: Path) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import SimpleDocTemplate

    if "Arial" not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(TTFont("Arial", str(FONT_REGULAR)))
        pdfmetrics.registerFont(TTFont("Arial-Bold", str(FONT_BOLD)))
        pdfmetrics.registerFontFamily("Arial", normal="Arial", bold="Arial-Bold")

    accents = ["#1F3A5F", "#3B3B3B", "#0F4C5C", "#4A2E2E"]
    accent = accents[sum(resume["slug"].encode()) % len(accents)]
    document = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=20 * 2.83465,
        rightMargin=20 * 2.83465,
        topMargin=16 * 2.83465,
        bottomMargin=16 * 2.83465,
        title=f"Резюме — {resume['name']}",
        author=resume["name"],
    )
    document.build(_pdf_story(resume, accent))


